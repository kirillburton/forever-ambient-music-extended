#!/usr/bin/env python3
"""Generate ForeverAmbientMusicExtended/ForeverPlaces.lua: where the Forever
client itself plays FAME's built-in tracks.

    python3 tools/make_forever_places.py

FAME places its tracks by tag (Zones.lua), which is how a track reaches zones
the game never gave it.  But many of them -- most of the Forever soundtrack --
the client already assigns, area by area, in its own ZoneMusic, and the tags
alone kept some out of the very places Forever wrote them for: Felwood's
cursed-land music out of Felwood, Un'Goro's soggy-place music out of Un'Goro.

So this follows the Forever client's AreaTable (an area with no music of its
own inherits its parent's, as in the game) and records, for every built-in
track, the Forever areas whose music set includes it.  FAME plays a track in
those areas whatever its tags say: the zone's own area means the whole zone,
a subzone means only that subzone.  The tags still decide everywhere else.

Left out as plain mistakes: areas named "DELETE ME" or "UNUSED", and anything
outside the zones FAME covers (instances, battlegrounds), where the game's own
rules apply anyway.

Inputs: tools/cache/db2/{AreaTable,ZoneMusic,SoundKitEntry}.csv (the wowf
branch, cached by the other tools), Tracks.lua and Originals.lua.
"""

import collections
import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB2 = os.path.join(ROOT, "tools", "cache", "db2")
ADDON = os.path.join(ROOT, "ForeverAmbientMusicExtended")
OUT = os.path.join(ADDON, "ForeverPlaces.lua")
MISTAKES = re.compile(r"DELETE ME|UNUSED", re.I)


def read(name):
    with open(os.path.join(DB2, name), newline="") as f:
        return list(csv.DictReader(f))


def lua_string(text):
    return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    areas = {int(r["ID"]): r for r in read("AreaTable.csv")}
    music = {int(r["ID"]): r for r in read("ZoneMusic.csv")}
    kits = collections.defaultdict(set)
    for r in read("SoundKitEntry.csv"):
        kits[int(r["SoundKitID"])].add(int(r["FileDataID"]))
    builtin = {int(m) for m in re.findall(r"\{ id = (\d+),",
                                          open(os.path.join(ADDON, "Tracks.lua")).read())}
    zones = {int(a): int(m) for m, a in re.findall(
        r"\[(\d+)\] = \{ area = (\d+),", open(os.path.join(ADDON, "Originals.lua")).read())}

    def music_set(area):
        for _ in range(10):
            if area not in areas:
                return 0
            if int(areas[area]["ZoneMusic"]):
                return int(areas[area]["ZoneMusic"])
            area = int(areas[area]["ParentAreaID"])
        return 0

    def tracks(set_id):
        if set_id not in music:
            return set()
        return (kits[int(music[set_id]["Sounds_0"])] | kits[int(music[set_id]["Sounds_1"])]) & builtin

    def zone_of(area):
        for _ in range(10):
            parent = int(areas[area]["ParentAreaID"]) if area in areas else 0
            if not parent:
                return area
            area = parent
        return area

    at, subzones = collections.defaultdict(set), {}
    for area, row in areas.items():
        zone_area = zone_of(area)
        if zone_area not in zones or MISTAKES.search(row["AreaName_lang"]):
            continue
        here = tracks(music_set(area))
        if area != zone_area:
            # A subzone playing what its zone plays adds nothing.
            here -= tracks(music_set(zone_area))
            if not here:
                continue
            subzones[area] = (zones[zone_area], row["AreaName_lang"])
        for fid in here:
            at[fid].add(area)

    lines = [
        "-- ForeverPlaces.lua -- generated by tools/make_forever_places.py.  Do not hand-edit.",
        "--",
        "-- Where the Forever client itself plays FAME's built-in tracks, from its own",
        "-- AreaTable and ZoneMusic: [fileDataID] = { Forever area IDs }.  A zone's own",
        "-- area means all of it, a subzone only that subzone.  FAME plays a track",
        "-- there whatever its tags say; the tags decide everywhere else.",
        "",
        "local ADDON, ns = ...",
        "",
        "ns.foreverAt = {",
    ]
    for fid in sorted(at):
        lines.append("    [%d] = { %s }," % (fid, ", ".join(map(str, sorted(at[fid])))))
    lines += [
        "}",
        "",
        "-- Subzones with music of their own: [areaID] = { uiMapID, English name }.",
        "ns.foreverAreas = {",
    ]
    for area in sorted(subzones):
        mapID, name = subzones[area]
        lines.append("    [%d] = { %d, %s }," % (area, mapID, lua_string(name)))
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("%d built-in tracks placed by the Forever client, %d subzones -> %s" % (
        len(at), len(subzones), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
