#!/usr/bin/env python3
"""Generate ForeverAmbientMusicExtended/Tracks.lua from the wago.tools data.

    python3 tools/fetch_music_list.py                                    # 1
    python3 tools/probe_durations.py --from-csv tools/cache/music_list.csv --pool
    python3 tools/make_tracks.py                                         # 3

Inputs
  tools/cache/music_list.csv    fileDataID,path,era,skip,tags  (step 1)
  tools/cache/durations.json    fileDataID -> seconds          (step 2)
  tools/tag_overrides.csv       hand corrections; empty tags drops a track

A track is written out only if it is in the extension pool, has a measured
duration of at least MIN_SECONDS, and ends up with at least one biome tag --
the matcher requires one, because a track with no sense of place would
otherwise pass the biome check everywhere.
"""

import argparse
import csv
import json
import os
import sys
from collections import OrderedDict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wagolib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MIN_SECONDS = 30

ERA_ORDER = ["classic", "forever", "cata", "mop", "wod", "legion", "bfa", "sl",
             "df", "tww", "midnight", "other"]
ERA_LABEL = {
    "classic": "Classic (zones Forever does not put these in rotation for)",
    "forever": "Forever (sound/music/forever)",
    "cata": "Cataclysm", "mop": "Mists of Pandaria", "wod": "Warlords of Draenor",
    "legion": "Legion", "bfa": "Battle for Azeroth", "sl": "Shadowlands",
    "df": "Dragonflight", "tww": "The War Within", "midnight": "Midnight",
    "other": "Other",
}

# A track needs at least one of these to be placeable.  Mood-only tracks get
# dropped rather than played in a zone that merely shares an adjective.
BIOMES = {
    "forest", "darkforest", "enchanted", "jungle", "swamp", "plains", "barrens",
    "desert", "mountain", "snow", "volcanic", "coast", "sea", "cave",
    "underground", "ruins", "blighted", "void", "arcane", "elemental", "sky",
    "city", "town", "tavern",
}

PLACEABLE = {
    "forest", "darkforest", "enchanted", "jungle", "swamp", "plains", "barrens",
    "desert", "mountain", "snow", "volcanic", "coast", "sea", "cave",
    "underground", "ruins", "blighted", "void", "arcane", "elemental", "sky",
    "city", "town", "tavern",
    "human", "dwarf", "gnome", "nightelf", "highelf", "orc", "tauren", "troll",
    "undead", "goblin", "naga", "draenei", "pandaren", "titan", "dragon",
    "demon", "centaur", "tuskarr", "earthen", "arathi", "kultiran", "drust",
    "vrykul", "nerubian", "wild",
}


def read_overrides(path):
    out = {}
    if not os.path.exists(path):
        return out
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            fdid, _, tags = line.partition(",")
            out[fdid.strip()] = tags.split()
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", default=os.path.join(wagolib.CACHE_DIR, "music_list.csv"))
    ap.add_argument("--durations", default=os.path.join(wagolib.CACHE_DIR, "durations.json"))
    ap.add_argument("--overrides", default=os.path.join(ROOT, "tools", "tag_overrides.csv"))
    ap.add_argument("-o", "--out",
                    default=os.path.join(ROOT, "ForeverAmbientMusicExtended", "Tracks.lua"))
    args = ap.parse_args()

    durations = json.load(open(args.durations))
    overrides = read_overrides(args.overrides)

    by_era = OrderedDict((e, []) for e in ERA_ORDER)
    dropped = {"not_in_pool": 0, "no_duration": 0, "too_short": 0,
               "override_drop": 0, "unplaceable": 0}

    with open(args.list) as f:
        for row in csv.DictReader(f):
            fdid, path = row["fileDataID"], row["path"]
            if not wagolib.in_extension_pool(path):
                dropped["not_in_pool"] += 1
                continue
            if fdid not in durations:
                dropped["no_duration"] += 1
                continue
            seconds = float(durations[fdid])
            if seconds < MIN_SECONDS:
                dropped["too_short"] += 1
                continue
            tags = overrides.get(fdid, row["tags"].split())
            if not tags:
                dropped["override_drop" if fdid in overrides else "unplaceable"] += 1
                continue
            if not (set(tags) & BIOMES):
                # No biome means no sense of place: the matcher would refuse
                # it everywhere.  Pin one in tag_overrides.csv to keep it.
                dropped["unplaceable"] += 1
                continue
            by_era[row["era"]].append((int(fdid), path, int(round(seconds)), tags))

    total = sum(len(v) for v in by_era.values())
    lines = [
        "-- Tracks.lua -- generated by tools/make_tracks.py.  Do not hand-edit:",
        "-- put corrections in tools/tag_overrides.csv and regenerate.",
        "--",
        "-- Every fileDataID here is in the World of Warcraft: Forever beta client",
        "-- (wago.tools branch wow_classic_beta), and every `len` is the file's real",
        "-- duration in seconds, measured with ffprobe.  `len` matters because",
        "-- PlayMusic() loops forever and fires no end event -- the addon stops the",
        "-- track on a timer, so a wrong length either truncates it or loops it.",
        "--",
        "-- %d tracks." % total,
        "",
        "local ADDON, ns = ...",
        "",
        "ns.builtinTracks = {",
    ]
    for era in ERA_ORDER:
        entries = by_era[era]
        if not entries:
            continue
        lines.append("")
        lines.append("    -- ===== %s (%d) =====" % (ERA_LABEL[era], len(entries)))
        for fdid, path, seconds, tags in sorted(entries, key=lambda e: e[1]):
            taglist = ", ".join('"%s"' % t for t in tags)
            lines.append('    { id = %-9s len = %4d, tags = { %s } },%s-- %s'
                         % ("%d," % fdid, seconds, taglist,
                            " " * max(1, 64 - len(taglist)), path.split("/", 2)[2]))
    lines += ["}", ""]

    with open(args.out, "w") as f:
        f.write("\n".join(lines))

    print("%s: %d tracks" % (args.out, total))
    for era in ERA_ORDER:
        if by_era[era]:
            print("    %-9s %d" % (era, len(by_era[era])))
    print("dropped: " + ", ".join("%s=%d" % kv for kv in dropped.items()))


if __name__ == "__main__":
    main()
