#!/usr/bin/env python3
"""Generate LocalTracks.lua from the audio files in the addon's Music folder.

    python3 tools/local_tracks.py                 # scan and write
    python3 tools/local_tracks.py --retag         # re-guess tags from scratch
    python3 tools/local_tracks.py --list          # show what it found, write nothing

Reads the real duration of each file with ffprobe, because PlayMusic() loops
and the addon needs to know when to stop.  Tags get a first-pass guess from
the file name using the same keyword table as the built-in tracks; hand-edit
them in LocalTracks.lua afterwards.

Tags you have already edited are preserved across re-runs, matched on the file
name.  Pass --retag to throw them away and start from the name again.

Nothing Blizzard-owned is bundled with this addon -- these are files you
extracted from your own install.  See the README.
"""

import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wagolib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADDON = "ForeverAmbientMusicExtended"
MUSIC_DIR = os.path.join(ROOT, ADDON, "Music")
OUT = os.path.join(ROOT, ADDON, "LocalTracks.lua")
AUDIO_EXT = (".mp3", ".ogg")

HEADER = '''-- LocalTracks.lua -- music you extracted from your own retail install.
--
-- Generated by tools/local_tracks.py from the files in this addon's Music
-- folder.  No Blizzard audio is bundled or distributed with this addon; these
-- entries only point at files already on your disk.  See the README for the
-- extraction steps.
--
-- A `file` path is relative to the Interface folder, and the file has to be in
-- place before the game client starts -- the client indexes addon files at
-- launch, so a file dropped in while logged in will not play until you
-- restart (a /reload is not enough).
--
-- Tags were guessed from the file name.  Fix them here; re-running
-- tools/local_tracks.py keeps your edits.
--
-- %d tracks.

local ADDON, ns = ...

ns.localTracks = {
'''

EMPTY_BODY = '''    -- { file = "Interface\\\\AddOns\\\\ForeverAmbientMusicExtended\\\\Music\\\\example.mp3",
    --   len = 183, tags = { "forest", "human", "calm" } },
'''

ENTRY_RE = re.compile(
    r'\{\s*file\s*=\s*"(?P<path>[^"]+)"\s*,\s*(?:name\s*=\s*"[^"]*"\s*,\s*)?len\s*=\s*(?P<len>\d+)\s*,'
    r'\s*tags\s*=\s*\{(?P<tags>[^}]*)\}', re.S)


def existing_tags(path):
    """{basename -> [tags]} from the LocalTracks.lua already on disk."""
    out = {}
    if not os.path.exists(path):
        return out
    text = open(path).read()
    # Ignore the commented-out example block.
    text = "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("--"))
    for m in ENTRY_RE.finditer(text):
        name = m.group("path").replace("\\\\", "\\").split("\\")[-1]
        tags = re.findall(r'"([^"]+)"', m.group("tags"))
        if tags:
            out[name] = tags
    return out


def ffprobe_seconds(path):
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", path],
        capture_output=True, text=True, check=True).stdout.strip()
    return float(out)


def scan():
    found = []
    for dirpath, _, names in os.walk(MUSIC_DIR):
        for name in sorted(names):
            if name.lower().endswith(AUDIO_EXT):
                found.append(os.path.join(dirpath, name))
    return sorted(found)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--retag", action="store_true", help="re-guess all tags from file names")
    ap.add_argument("--list", action="store_true", help="report only, write nothing")
    args = ap.parse_args()

    if not os.path.isdir(MUSIC_DIR):
        print("no Music folder at %s" % MUSIC_DIR)
        return
    files = scan()
    keep = {} if args.retag else existing_tags(OUT)

    rows, failed = [], []
    for full in files:
        rel = os.path.relpath(full, os.path.join(ROOT, ADDON))
        name = os.path.basename(full)
        try:
            seconds = int(round(ffprobe_seconds(full)))
        except Exception as exc:                      # noqa: BLE001
            failed.append((rel, exc))
            continue
        tags = keep.get(name) or wagolib.guess_tags(rel.replace(os.sep, "/").lower())
        lua_path = "Interface\\\\AddOns\\\\%s\\\\%s" % (ADDON, rel.replace(os.sep, "\\\\"))
        rows.append((lua_path, seconds, tags, name, bool(keep.get(name))))

    for rel, exc in failed:
        print("  SKIPPED %s: %s" % (rel, exc))

    untagged = [r for r in rows if not r[2]]
    if args.list or not rows:
        for lua_path, seconds, tags, name, kept in rows:
            print("  %5ds  %-45s %s%s" % (seconds, name, " ".join(tags) or "(no tags)",
                                          "  [kept]" if kept else ""))
        if not rows:
            print("no .mp3 or .ogg files in %s" % MUSIC_DIR)
        if args.list:
            return

    body = []
    for lua_path, seconds, tags, name, _ in rows:
        taglist = ", ".join('"%s"' % t for t in tags)
        body.append('    { file = "%s",' % lua_path)
        body.append('      name = "%s", len = %d, tags = { %s } },'
                    % (os.path.splitext(name)[0], seconds, taglist))
    text = (HEADER % len(rows)) + ("\n".join(body) + "\n" if body else EMPTY_BODY) + "}\n"
    with open(OUT, "w") as f:
        f.write(text)

    print("%s: %d tracks" % (OUT, len(rows)))
    if untagged:
        print("%d have no tags and will never be picked -- tag them in LocalTracks.lua:"
              % len(untagged))
        for r in untagged:
            print("    %s" % r[3])


if __name__ == "__main__":
    main()
